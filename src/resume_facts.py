"""Writes reports/RESUME_FACTS.md: only numbers read directly from this run's output tables."""
import json

import pandas as pd

from src import config as C

T = C.TABLE_DIR


def main() -> None:
    log = pd.read_csv(T / "cleaning_log.csv").set_index("rule")
    raw = int(log.loc["TOTAL raw rows loaded", "rows_dropped"])
    kept = int(log.loc["TOTAL rows after cleaning", "rows_dropped"])
    dropped_pct = float(log.loc["TOTAL dropped", "pct_of_raw_dropped"])
    files = pd.read_csv(T / "raw_files_used.csv")
    zh = pd.read_parquet(C.PROCESSED_DIR / "zone_hourly.parquet", columns=["zone_id", "hour_ts"])
    conc = pd.read_csv(T / "eda_zone_concentration.csv").iloc[0]
    meta = json.loads((T / "forecast_meta.json").read_text())
    fs = pd.read_csv(T / "forecast_summary.csv")
    inf = json.loads((T / "inference_meta.json").read_text())
    lg, ts = inf["logit"], inf["tests"]
    coefs = pd.read_csv(T / "logit_coefficients.csv").set_index("term")
    win = pd.read_csv(T / "finding_windows.csv").set_index("comparison")

    def f(model, h, col):
        return fs[(fs.model == model) & (fs.horizon == h)][col].iloc[0]

    def orr(term):
        r = coefs.loc[term]
        return f"{r.odds_ratio:.2f} (95% CI {r.or_ci_low:.2f}-{r.or_ci_high:.2f}, p={r.p_value:.2g})"

    def w(name):
        r = win.loc[name]
        return f"{r.ratio_A_over_B:.2f}x (95% CI {r.ratio_ci_low:.2f}-{r.ratio_ci_high:.2f})"

    cs168 = f("calendar_sarima", 168, "MAE_ratio_vs_snaive_168")
    lines = [
        "# Resume facts (generated by src/resume_facts.py from reports/tables)",
        "",
        "Every number below is read from this run's output files. Rounding is the only change.",
        "",
        "## Data",
        f"- Source: NYC TLC Yellow Taxi trip records, {len(files)} monthly Parquet files (Jan-Dec {C.YEAR}).",
        f"- Raw rows loaded: {raw:,}",
        f"- Rows after cleaning: {kept:,} ({dropped_pct:.2f}% dropped by 7 explicit rules, logged per rule)",
        f"- Taxi zones in the hourly grid: {zh.zone_id.nunique()} (pickups recorded in {int(conc.zones_with_any_pickup)})",
        f"- Hours in the grid: {zh.hour_ts.nunique():,}; zone-hour rows: {len(zh):,}",
        f"- Zones with >= {C.ACTIVE_ZONE_MIN_DAILY_MEAN} pickups/day used for inference: {ts['n_zones_tested']}",
        "",
        "## Forecasting (citywide hourly pickups, rolling origin, expanding window)",
        f"- Folds: {meta['n_folds']}; horizons 24h and 168h; baseline = seasonal naive lag 168",
        f"- 168h: calendar_sarima MASE {f('calendar_sarima', 168, 'MASE'):.3f} vs seasonal naive "
        f"{f('snaive_168', 168, 'MASE'):.3f}; MAE ratio {cs168:.3f} ({(1 - cs168) * 100:.1f}% lower MAE); "
        f"better in {int(f('calendar_sarima', 168, 'folds_beating_snaive_168'))} of {meta['n_folds']} folds",
        f"- 24h: calendar_sarima MASE {f('calendar_sarima', 24, 'MASE'):.3f} vs seasonal naive "
        f"{f('snaive_168', 24, 'MASE'):.3f}; MAE ratio {f('calendar_sarima', 24, 'MAE_ratio_vs_snaive_168'):.3f}; "
        f"better in {int(f('calendar_sarima', 24, 'folds_beating_snaive_168'))} of {meta['n_folds']} folds. "
        "Does NOT beat the baseline at 24h.",
        f"- First SARIMA specification (daily differencing + Fourier): MAE ratio vs baseline "
        f"{f('sarimax', 168, 'MAE_ratio_vs_snaive_168'):.2f} at 168h, {f('sarimax', 24, 'MAE_ratio_vs_snaive_168'):.2f} "
        "at 24h (worse than baseline)",
        f"- MSTL seasonal strength: daily {meta['strength_daily']:.2f}, weekly {meta['strength_weekly']:.2f}",
        "",
        "## Hypothesis tests (weekday vs weekend daily pickups per zone)",
        f"- Zones tested: {ts['n_zones_tested']}; test: {ts['primary_test']} "
        f"(chosen because {ts['share_zones_nonnormal_shapiro'] * 100:.0f}% of zones reject normality)",
        f"- Significant at p<0.05 before correction: {ts['n_sig_raw']}",
        f"- Significant after Benjamini-Hochberg (FDR 5%): {ts['n_sig_bh']} "
        f"({ts['n_sig_bh_weekend_higher']} busier on weekends, {ts['n_sig_bh_weekend_lower']} quieter)",
        f"- Nulls after correction: {ts['n_null_bh']}",
        "",
        "## Logit (zone-hour above its zone's 75th percentile; two-way clustered SEs)",
        f"- Rows: {lg['n_rows']:,} zone-hours, {lg['n_zones']} zones",
        f"- Odds ratio, 16-19h vs 10-15h: {orr('block[pm_peak_16_19]')}",
        f"- Odds ratio, 00-05h vs 10-15h: {orr('block[night_00_05]')}",
        f"- Odds ratio, holiday: {orr('holiday')}",
        f"- Odds ratio, weekend: {orr('weekend')} (CI includes 1)",
        f"- Max VIF: {pd.read_csv(T / 'logit_vif.csv').VIF.max():.2f}",
        f"- Oct-Dec holdout: AUC {lg['calib_auc']:.3f}, Brier {lg['calib_brier']:.3f} "
        f"(constant-rate Brier {lg['calib_brier_constant_train_rate']:.3f}); "
        f"mean predicted {lg['calib_mean_predicted_holdout']:.3f} vs observed {lg['calib_holdout_positive_rate']:.3f}: "
        "under-predicts out of time, not well calibrated",
        "",
        "## Effect sizes behind the findings",
        f"- Citywide Tue-Thu 17-19h vs 10-15h pickups/hour: {w('Citywide Tue-Thu 17-19h vs Tue-Thu 10-15h')}",
        f"- Manhattan Sat/Sun 00-02h vs Mon-Thu 00-02h: {w('Manhattan Sat-Sun 00-02h vs Mon-Thu 00-02h')}",
        f"- Top 10 zones' share of all pickups: {conc.top10_share_pct:.1f}%; zones covering 80% of pickups: "
        f"{int(conc.zones_for_80pct)}",
        "",
        "## Do not claim",
        "- That a model beats the seasonal naive at the 24h horizon.",
        "- Undersupply or unmet demand (no supply data; pickups are completed trips).",
        "- Weather, events or multi-year effects (not in the data).",
        "- The logit as a calibrated probability model.",
    ]
    out = C.REPORTS_DIR / "RESUME_FACTS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
